  // Trous intérieurs (non reliés au bord) = les yeux → rendus en gris clair par-dessus le corps
  function shadow(grid, withEyes) {
    var rows = grid.length, cols = grid[0].length;
    var R = rows + 2, C = cols + 2;
    function solid(r, c) { return r >= 0 && c >= 0 && r < rows && c < cols && grid[r][c] === '#'; }
    var reach = []; for (var i = 0; i < R; i++) reach.push(new Array(C).fill(false));
    var stack = [[0, 0]]; reach[0][0] = true;
    while (stack.length) {
      var p = stack.pop(), r = p[0], c = p[1];
      var nb = [[r + 1, c], [r - 1, c], [r, c + 1], [r, c - 1]];
      for (var k = 0; k < 4; k++) {
        var nr = nb[k][0], nc = nb[k][1];
        if (nr < 0 || nc < 0 || nr >= R || nc >= C || reach[nr][nc]) continue;
        if (!solid(nr - 1, nc - 1)) { reach[nr][nc] = true; stack.push([nr, nc]); }
      }
    }
    var body = [], eyes = [];
    for (var y = 0; y < rows; y++) {
      for (var x = 0; x < cols; x++) {
        if (grid[y][x] === '#') body.push((x * U) + 'px ' + (y * U) + 'px 0 0 ' + BODY);
        // trou intérieur dans la zone de la tête (haut) = œil ; on ignore les poches d'ailes plus bas
        else if (withEyes && !reach[y + 1][x + 1] && y < rows * 0.46) eyes.push((x * U) + 'px ' + (y * U) + 'px 0 0 ' + EYE);
      }
    }
    return eyes.concat(body).join(',');   // yeux en premier = au premier plan
  }

